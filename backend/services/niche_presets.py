GRAY, BLUE, TEAL, AMBER, VIOLET, GREEN, RED, DARK = (
    "#6B7280", "#3B82F6", "#0D9488", "#D97706", "#7C3AED", "#10B981", "#EF4444", "#1F2937")


def _stages(*middle):
    """Воронка: Новый (new) → свои этапы → Успех (success) / Отказ / Не беспокоить."""
    first, rest = middle[0], middle[1:]
    stages = [{"key": "new", "label": first, "color": GRAY, "kind": "open"}]
    colors = [BLUE, TEAL, AMBER, VIOLET, BLUE, TEAL]
    won = None
    for i, item in enumerate(rest):
        key, label = item
        if key == "success":
            won = label
            continue
        stages.append({"key": key, "label": label, "color": colors[i % len(colors)], "kind": "open"})
    stages.append({"key": "success", "label": won or "Успех", "color": GREEN, "kind": "won"})
    stages.append({"key": "rejected", "label": "Отказ", "color": RED, "kind": "lost"})
    stages.append({"key": "do_not_call", "label": "Не беспокоить", "color": DARK, "kind": "lost"})
    return stages


