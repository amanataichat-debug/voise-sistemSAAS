def _merge_questions(base: List[dict], extra: Optional[List[dict]]) -> List[dict]:
    out = deepcopy(base)
    for q in extra or []:
        hit = next((x for x in out if x["key"] == q["key"]), None)
        if hit:
            hit.update({k: v for k, v in q.items() if k != "key"})
        else:
            out.insert(0, deepcopy(q))
    return out


def preset(niche_key: Optional[str]) -> Dict[str, Any]:
    """Полный пресет ниши: группа + уточнения. Неизвестная ниша — «Другое»."""
    item = niche_item(niche_key) or niche_item("other")
    group = item.get("group", "other")
    g = deepcopy(GROUPS.get(group, GROUPS["other"]))
    o = NICHE_OVERRIDES.get(item["key"], {})
    out = {
        "niche": item["key"],
        "group": group,
        "title": item["title"],
        "icon": item["icon"],
        "goal": o.get("goal", g["goal"]),
        "questions": _merge_questions(g["questions"], o.get("questions")),
        "catalog": {**g["catalog"], **(o.get("catalog") or {})},
        "pipeline": deepcopy(o.get("pipeline") or g["pipeline"]),
        "collections": list(o.get("collections") or []),
        "ask": list(o.get("ask") or g["ask"]),
        "kb": list(o.get("kb") or g["kb"]) + list(o.get("kb_extra") or []),
        "analytics": list(o.get("analytics") or g["analytics"]),
    }
    if o.get("crm_default"):
        for q in out["questions"]:
            if q["key"] == "crm":
                q["default"] = o["crm_default"]
    return out


def default_answers(niche_key: Optional[str]) -> Dict[str, str]:
    return {q["key"]: q.get("default") for q in preset(niche_key)["questions"]}


def modules_for(niche_key: Optional[str], answers: Optional[Dict[str, Any]] = None) -> Dict[str, bool]:
    """
    Какие модули включены. Чаты, клиенты, каталог, база знаний, аналитика, звонки — всегда;
    запись / воронка CRM / заказы — по модели работы и ответам владельца.
    """
    p = preset(niche_key)
    a = {**default_answers(niche_key), **{k: v for k, v in (answers or {}).items() if v is not None}}
    group = p["group"]
    yes = lambda key: str(a.get(key, "")).lower() in ("yes", "1", "true")  # noqa: E731
    booking = crm = orders = False
    if group == "booking":
        booking, crm = True, yes("crm")
    elif group == "shop":
        orders, crm = True, yes("crm")
    elif group == "deals":
        booking, crm = yes("meetings"), True
    elif group == "auto":
        booking, crm, orders = yes("booking"), True, yes("parts")
    elif group == "food":
        orders, booking, crm = True, yes("tables"), False   # заказы у еды всегда (с собой / доставка)
    elif group == "education":
        booking, crm = yes("trial"), True
    else:
        model = a.get("model") or "deals"
        booking, orders, crm = model == "booking", model == "sales", yes("crm")
    return {"chats": True, "calls": True, "clients": True, "catalog": True, "knowledge": True, "analytics": True,
            "booking": booking, "crm": crm, "orders": orders}


def catalog_payload() -> Dict[str, Any]:
    """Справочник для экрана выбора: ниши с вопросами и значениями по умолчанию."""
    from backend.services.niche_catalog import NICHE_GROUPS
    out = []
    for n in NICHES:
        p = preset(n["key"])
        out.append({**n, "questions": p["questions"], "goal": p["goal"], "catalog_title": p["catalog"]["title"]})
    return {"groups": NICHE_GROUPS, "niches": out}
