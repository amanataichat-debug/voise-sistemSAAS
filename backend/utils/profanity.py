"""
Нецензурная лексика — запрет на уровне кода для ВСЕЙ платформы (18.11.2026, звонок 17478409:
клиент возмутился «охуенно говорите, не стыдно вам?» — агент продающей компании матерится).

Одна реализация на все каналы:
  - голос «речь в речь» (GPT-Live, Gemini Live) по телефону: адаптер звонка (`sip_media_adapter.HandlerSocket`)
    читает стенограмму ответа агента; мат → обрывает звук в линии и велит агенту извиниться;
  - каскад Voksy Voice (текст → синтез): слово вырезается из текста ДО синтеза (`handler_fish._say`);
  - переписка (WhatsApp / Telegram / Instagram): `message_style.clean_client_text` вырезает слово из текста агента.
Текст, который владелец пишет сам, не трогается.

Подход — по словам (токенам), а не подстрокой: «застрахуем», «тихую», «себе», «небо», «сукно», «мудрый»,
«сиз» не должны срабатывать. Латинские буквы-двойники (o, a, e, x, y, p, c) приводятся к кириллице.
"""

from __future__ import annotations

import re
from typing import List

_LOOKALIKE = str.maketrans({
    "a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "x": "х", "y": "у", "k": "к", "m": "м",
    "t": "т", "b": "б", "h": "н", "ё": "е", "3": "з", "0": "о", "@": "а",
})

# Приставки, с которыми корни мата встречаются в начале слова
_PFX = r"(?:на|по|за|от|до|вы|при|пере|об|о|у|с|раз|рас|недо|под|ни|ох|а|е|про)?"
_PFX_HARD = r"(?:за|у|вы|на|до|от[ъь]?|про|по|при|съ|въ|разъ|подъ|объ|изъ|недо|пере)"

_RU_PATTERNS = [
    rf"^{_PFX}ху[йяеиюё]",                                  # хуй, охуенно, нахуй, похуй, хуёво
    r"п[иеё]зд",                                            # пизд-, пезд-
    r"^[её]б(?:а[тлнш]|ан|ал|ну|ут|уч|ло|л[аои]|ись|ош|ыр|[её]т|н|ищ|ак)",  # ебать, ебан, ебло, ебнуть
    rf"^{_PFX_HARD}[её]б(?:а|у|л|н|ис|и|ыв|о|ну|[её]т)",    # заебал, уебок, выебываться, отъебись
    r"долбо[её]б",
    r"^бля(?:$|д|т|ть|ха|ди|дь|дс)",                        # бля, блядь, блять (не «бляшка»)
    r"^муда[кч]|^мудил|^мудо[зх]",
    r"^пид[оа]?р|^пидорас",
    r"залуп",
    r"^с[уy]к(?:а|и|у|е|ой|ам|ами|ах)$|^сучк|^сучар",
    r"^г[оа]ндон",
    r"^шлюх",
    r"^говн|^дерьм|^жоп[аеуыо]",
    r"^(?:за|об|на|по)?сра(?:ть|н|л)|^обосра|^засра",
    r"^дроч",                                               # не «драчун»
    r"^манд[ауое]$|^мандой$|^мандавош",                     # не «мандарин», «мандат», «мандала»
]
# Кыргызский мат (корень сиг-/сик-, «энеңди…», «амыңды»): «сиз», «сиздин» не задеваются
_KY_PATTERNS = [
    r"^сиг(?:е|и|ей|ем|ип|ил)",
    r"^сик(?:ти|кен|ейин|ем|ип)",
    r"^энеңди$|^энеңдин$",
    r"^амы[ңн]ды$|^амыңа$",
]
_EN_PATTERNS = [
    r"fuck", r"^shit", r"bitch", r"asshole", r"motherf", r"^cunt", r"^dick(?:head)?$",
]

_RU_RE = [re.compile(p) for p in _RU_PATTERNS + _KY_PATTERNS]
_EN_RE = [re.compile(p) for p in _EN_PATTERNS]
_TOKEN_RE = re.compile(r"[A-Za-zА-Яа-яЁёҢңӨөҮү0-9@*]+")


def _is_bad_token(raw: str) -> bool:
    low = raw.lower()
    if any(rx.search(low) for rx in _EN_RE):
        return True
    norm = low.translate(_LOOKALIKE).replace("*", "")
    if not norm or not re.search(r"[а-яңөү]", norm):
        return False
    return any(rx.search(norm) for rx in _RU_RE)


def find_profanity(text: str) -> List[str]:
    """Нецензурные слова в тексте (как написаны)."""
    if not text:
        return []
    return [m.group(0) for m in _TOKEN_RE.finditer(text) if _is_bad_token(m.group(0))]


def has_profanity(text: str) -> bool:
    return bool(find_profanity(text))


def strip_profanity(text: str) -> str:
    """Вырезать нецензурные слова, поправить пробелы и знаки вокруг. Чистый текст возвращается как есть."""
    if not text or not has_profanity(text):
        return text
    def _cut(m):
        return "" if _is_bad_token(m.group(1)) else m.group(0)

    # слово вместе с запятой после него: «Сука, круто» → «круто», «Это охуенно, правда» → «Это правда»
    out = re.sub(r"([A-Za-zА-Яа-яЁёҢңӨөҮү0-9@*]+)(?:\s*,)?", _cut, text)
    out = re.sub(r"[ \t]{2,}", " ", out)
    out = re.sub(r" +([,.!?…:;])", r"\1", out)
    out = re.sub(r"([,:;])\s*([,.!?…])", r"\2", out)
    out = re.sub(r"([.!?…])\s*,", r"\1", out)
    out = re.sub(r"^\s*[,.;:!?…-]+\s*", "", out)
    out = re.sub(r"(?m)^[ \t]+", "", out)
    # первая буква предложения после вырезанного слова — заглавная
    out = re.sub(r"(^|[.!?…]\s+)([а-яёa-zңөү])", lambda m: m.group(1) + m.group(2).upper(), out)
    return out.strip()


