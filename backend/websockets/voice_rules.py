# GPT-Live: голосовой слой + бэкенд делегирования (шаблон OpenAI live-prompting §5.1, метки оставлены как есть).
LIVE_DELEGATION_RULES = """

Delegation policy:
Delegate to the backend when: нужен поиск того, чего нет в инструкции; нужно действие (запись, письмо, завершение звонка); нужен расчёт.
Do not delegate to the backend when: ответ есть в инструкции и знаниях выше или в уже полученном результате; собеседник выбрал время или канал — подтверди сам; он просит менеджера, встречу или перезвонить — это передаст система после звонка, скажи сам одной фразой; нужен короткий уточняющий вопрос; приветствие, благодарность, просьба повторить.
Delegate before giving an answer that depends on backend work. Do not guess the result while waiting."""

# Gemini Live и Voksy Voice зовут функции сами.
TOOLS_RULES = """

Функции: ответ есть в инструкции и знаниях — отвечай сам, без вызова. Нет — вызови поиск коротким запросом по сути вопроса и дождись результата. Не вызывай больше двух функций подряд, ничего не сказав собеседнику; названия функций не произноси."""

# Voksy Voice (каскад): реплики собеседника — распознанный текст, ответ озвучит синтез речи.
CASCADE_RULES = """

Реплики собеседника — распознанная телефонная речь: бывают искажённые слова и смесь кыргызского с русским. Угадывай смысл по разговору; не уверен — назови догадку одним вопросом. Пиши так, как говорят вслух: без списков, markdown, эмодзи и ссылок, числа и время — словами. Никогда не завершай звонок из-за того, что не понял, — переспроси."""

TELEPHONY_RULES = """

Это телефонный звонок: связь бывает с шумом — говори короче и переспрашивай неясные имя, число или дату."""

MASCULINE_VOICES = {"cedar", "ash", "ballad", "echo", "verse", "ripple", "vesper", "stone", "meridian",
                    "tempo", "beacon", "cinder", "flitz", "sillage", "shida",
                    "puck", "charon", "fenrir", "orus"}
FEMININE_VOICES = {"marin", "coral", "sage", "shimmer", "quartz", "willow", "gleam", "bossa", "delta",
                   "nuri", "juni", "brise", "nira", "harema", "noeul",
                   "aoede", "kore", "leda", "callirrhoe", "sulafat", "zephyr"}


def voice_gender(voice: Optional[str]) -> Optional[str]:
    v = (voice or "").strip().lower()
    if v in MASCULINE_VOICES:
        return "m"
    if v in FEMININE_VOICES:
        return "f"
    return None


def gender_rule(voice: Optional[str]) -> str:
    g = voice_gender(voice)
    if g == "m":
        return ("\n\nТвой голос мужской: о себе говори в мужском роде («рад», «готов», «записал»), "
                "даже если инструкция выше написана иначе.")
    if g == "f":
        return ("\n\nТвой голос женский: о себе говори в женском роде («рада», «готова», «записала»), "
                "даже если инструкция выше написана иначе.")
    return ""


_KY_WORDS = ("саламатсыз", "салам", "кандайсыз", "жардам", "кантип", "рахмат", "сиз ", "мен ", "биз ", "ооба", "макул")


def greeting_language(greeting: Optional[str], fallback: Optional[str] = None) -> Optional[str]:
    """Язык фразы приветствия: кыргызские буквы/слова → ky, иная кириллица → ru, иначе fallback."""
    text = (greeting or "").strip().lower()
    if not text:
        return fallback
    if any(ch in text for ch in "ңөү") or any(w in text + " " for w in _KY_WORDS):
        return "ky"
    if any("а" <= ch <= "я" or ch == "ё" for ch in text):
        return "ru"
    return fallback


def start_language_rule(card_language: Optional[str], greeting: Optional[str]) -> str:
    """Одна строка: на каком языке начать (язык приветствия, иначе язык карточки)."""
    card = (card_language or "").strip().lower()[:2] or None
    lang = greeting_language(greeting, card)
    name = _LANGUAGE_NAMES.get(lang or "")
    if not name:
        return ""
    return f"\n\nЯзык начала этого звонка — на {name}."


def tool_rows(functions: Optional[List[Dict[str, Any]]], limit: int = 12) -> List[str]:
    """Одна строка на функцию: имя и первое предложение описания."""
    rows = []
    for f in functions or []:
        name = f.get("name") if isinstance(f, dict) else None
        if not name:
            continue
        desc = " ".join(str(f.get("description") or "").split())
        first = desc.split(". ")[0][:140].rstrip(".")
        rows.append(f"- {name}: {first}" if first else f"- {name}")
    return rows[:limit]


def build_voice_rules(engine: str, *, language: Optional[str] = None, greeting: Optional[str] = None,
                      voice: Optional[str] = None, functions: Optional[List[Dict[str, Any]]] = None,
                      telephony: bool = False) -> str:
    """
    Всё, что дописывается после промпта карточки. engine: "gpt_live" | "gemini" | "cascade".
    Кыргызский блок — всем: собеседник может перейти на кыргызский на любой карточке.
    """
    out = VOICE_RULES + KYRGYZ_RULES
    rows = tool_rows(functions)
    if engine == "gpt_live":
        out += LIVE_DELEGATION_RULES
        if rows:
            out += "\nBackend tools (названия собеседнику не произноси):\n" + "\n".join(rows)
    else:
        out += TOOLS_RULES
        if rows:
            out += "\nДоступные функции (названия собеседнику не произноси):\n" + "\n".join(rows)
        if engine == "cascade":
            out += CASCADE_RULES
    if telephony:
        out += TELEPHONY_RULES
    out += start_language_rule(language, greeting)
    out += gender_rule(voice)
    return out


def card_instructions(assistant_config, engine: str, *, functions=None, telephony: bool = False,
                      voice: Optional[str] = None, greeting: Optional[str] = None) -> str:
    """Промпт карточки + общие правила голоса (удобно для каскада: Voksy Voice и старые Fish)."""
    base = (getattr(assistant_config, "system_prompt", None) or "").strip() or "Ты вежливый голосовой помощник."
    return base + build_voice_rules(
        engine,
        language=getattr(assistant_config, "language", None),
        greeting=greeting if greeting is not None else getattr(assistant_config, "greeting_message", None),
        voice=voice,
        functions=functions,
        telephony=telephony,
    )
