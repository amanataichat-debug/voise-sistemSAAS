"""
Подсказки голосовой модели Gemini Live: та же манера и те же правила диалога, что у GPT-Live.

Раньше GPT-Live читал промпт карточки ПЛЮС большой блок правил (живость, смех, вдохи, краткость,
язык и кыргызский, перебивания, договорённость, завершение, материалы, приветствие, телефония, род по
голосу — см. live_client.py), а Gemini получал только голый промпт карточки: отсюда «промпт
заточен под GPT» и сухие, длинные ответы. Потом оба движка читали общие куски; после живого звонка 01.11.2026
у Gemini СВОЯ короткая манера (GEMINI_MANNER_HINT: живой разговор вместо «ответ + дежурный вопрос», понять
задачу человека, переспросить обрывок), а общими остались VOICE_DIALOG_RULES, VOICE_GREETING_RULE,
VOICE_TELEPHONY_HINT, voice_gender_hint. У каждого свой кусок про функции: у GPT-Live это делегирование
бэкенду, у Gemini — собственные вызовы.

По рекомендациям Google для Gemini Live (docs «Best practices with Gemini Live API», «Gemini 3.8 Live»;
полный разбор страниц — docs/gemini_live_3_8_reference.md, собран 01.11.2026):
- системная инструкция: роль → нормы диалога → ограничения (промпт карточки идёт первым, ниже — правила);
- у функций указывать, когда их вызывать; не больше двух вызовов подряд без реплики пользователю;
- «думающих» указаний («рассуждай по шагам») не давать — у 3.8 Live нет thinking;
- темп речи промптом не регулируется (Google это прямо пишет), поэтому здесь только «ровно и чётко»;
- язык модель определяет по речи сама, фиксируется инструкцией (она в GEMINI_MANNER_HINT).
Проактивный звук у 3.8 включён всегда и не отключается (proactive_audio=false → ошибка): модель сама решает,
не фоновая ли это речь, и на телефоне может промолчать там, где человек ждёт ответа — отсюда «разговор один на один» в
GEMINI_MANNER_HINT. Эмоциональный диалог (affective dialog) в 3.8 УДАЛЁН из API (страница модели:
«Affective dialogue is removed»), поля enable_affective_dialog в setup нет и быть не должно; смех, вдохи,
паузы, темп и аудио-теги документация Live не описывает — это только слова в промпте (GEMINI_MANNER_HINT).
Языка как поля нет (native audio сам выбирает язык, languageCode не поддерживается) — язык держит промпт;
Google советует усиливать капризные правила словом «unmistakably».
"""

