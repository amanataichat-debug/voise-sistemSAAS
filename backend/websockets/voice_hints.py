# backend/websockets/voice_hints.py
"""
Подсказки голосовой модели Gemini Live: та же манера и те же правила диалога, что у GPT-Live.

Раньше GPT-Live читал промпт карточки ПЛЮС большой блок правил (живость, смех, вдохи, краткость,
язык и кыргызский, перебивания, договорённость, завершение, материалы, приветствие, телефония, род по
голосу — см. live_client.py), а Gemini получал только голый промпт карточки: отсюда «промпт
заточен под GPT» и сухие, длинные ответы. Теперь общие куски (VOICE_MANNER_HINT, VOICE_DIALOG_RULES,
VOICE_GREETING_RULE, VOICE_TELEPHONY_HINT, voice_gender_hint) читают оба движка; у каждого свой только
кусок про функции: у GPT-Live это делегирование бэкенду, у Gemini — собственные вызовы.

По рекомендациям Google для Gemini Live (docs «Best practices with Gemini Live API», «Gemini 3.8 Live»;
полный разбор страниц — docs/gemini_live_3_8_reference.md, собран 01.11.2026):
- системная инструкция: роль → нормы диалога → ограничения (промпт карточки идёт первым, ниже — правила);
- у функций указывать, когда их вызывать; не больше двух вызовов подряд без реплики пользователю;
- «думающих» указаний («рассуждай по шагам») не давать — у 3.8 Live нет thinking;
- темп речи промптом не регулируется (Google это прямо пишет), поэтому здесь только «ровно и чётко»;
- язык модель определяет по речи сама, фиксируется инструкцией (она в VOICE_MANNER_HINT).
Проактивный звук у 3.8 включён всегда и не отключается (proactive_audio=false → ошибка): модель сама решает,
не фоновая ли это речь, и на телефоне может промолчать там, где человек ждёт ответа — отсюда правило
GEMINI_CONVERSATION_HINT. Эмоциональный диалог (affective dialog) в 3.8 УДАЛЁН из API (страница модели:
«Affective dialogue is removed»), поля enable_affective_dialog в setup нет и быть не должно; смех, вдохи,
паузы, темп и аудио-теги документация Live не описывает — это только слова в промпте (VOICE_MANNER_HINT).
Языка как поля нет (native audio сам выбирает язык, languageCode не поддерживается) — язык держит промпт;
Google советует усиливать капризные правила словом «unmistakably».
"""

from typing import Any, Dict, List, Optional

from backend.websockets.live_client import (
    VOICE_DIALOG_RULES,
    VOICE_GREETING_RULE,
    VOICE_MANNER_HINT,
    VOICE_TELEPHONY_HINT,
    voice_gender_hint,
)

# Инструкция карточки/агента (роль, цель, язык, порядок разговора, знания, правила звонка) ГЛАВНАЯ. Эти подсказки
# стоят в конце промпта, а модель сильнее слушает последнее, поэтому без явного приоритета они перебивали
# собственные правила агента (звонок 01.11.2026: агент заговорил по-русски после «алло», хотя в его промпте стоит
# «держись языка приветствия, не меняй язык из-за короткого «алло»»).
GEMINI_PRIORITY_NOTE = (
    "\n\nПРИОРИТЕТ ИНСТРУКЦИЙ. Всё, что написано выше (твоя роль, цель звонка, язык, порядок разговора, "
    "знания о компании, правила звонка и завершения), — главное и выполняется дословно. Ниже только общие правила "
    "манеры речи; если они хоть в чём-то расходятся с инструкцией выше, следуй инструкции выше."
)

# Разговорное поведение под особенности 3.8 Live: проактивный звук включён всегда и не отключается, поэтому
# модель отвечает не на каждую услышанную речь; язык фиксируется только промптом (по совету Google — словом
# «unmistakably»); лишнее эхо и дежурные вопросы Google прямо называет «DO NOT repeat… NO PLATITUDES».
GEMINI_CONVERSATION_HINT = (
    "\n\nКАК ВЕСТИ РАЗГОВОР. Это разговор один на один: всё, что говорит собеседник, обращено к тебе, "
    "посторонней речью считай только явный шум, музыку и чужие голоса рядом. ПОКА СОБЕСЕДНИК ГОВОРИТ — "
    "МОЛЧИ: никаких «мм», «угу», «понятно», «да-да» и подсказок поверх его речи, даже если он сделал паузу "
    "подумать посреди фразы. Отвечай, только когда он ясно закончил мысль или задал вопрос, и тогда — сразу, "
    "без долгого молчания. Не начинай ответ с пересказа его слов и не заканчивай каждую реплику дежурным "
    "«чем ещё могу помочь?» — вопрос задавай по делу, один. На одну реплику собеседника — одна твоя, "
    "короткая; продолжай мысль только когда он подтвердил, что интересно. "
    "YOU MUST SPEAK UNMISTAKABLY IN THE LANGUAGE OF YOUR GREETING (Russian or Kyrgyz) AND STAY IN IT. "
    "Switch to the other language ONLY when the caller says a whole phrase in it or asks you to; "
    "a single word, an accent or a short «алло» is NOT a reason to switch."
)

_LANGUAGE_NAMES = {"ky": "кыргызском", "kk": "казахском", "uz": "узбекском", "en": "английском", "tr": "турецком", "ru": "русском"}


def language_note(language: str) -> str:
    """
    Язык карточки для Gemini Live — тот же порядок, что в промпте звонков агента (VOICE_AGENT_PROMPT_BASE):
    начни на языке приветствия и держись его; смени язык, только если собеседник целой фразой заговорил на другом
    (русский или кыргызский) или попросил; одно слово, акцент и короткое «алло» — не повод.
    """
    name = _LANGUAGE_NAMES.get((language or "").strip().lower()[:2])
    if not name:
        return ""
    return (f"\n\nЯЗЫК РАЗГОВОРА. Начни на {name} языке (приветствие) и держись его. Смени язык (русский или "
            "кыргызский), только если собеседник целой фразой заговорил на другом языке или попросил об этом, а "
            "вернулся обратно — вернись и ты. Не меняй язык из-за акцента, одного слова или короткого «алло». "
            "Никогда не говори, что плохо владеешь русским или кыргызским: не расслышал — мягко переспроси на его языке.")


# Правило функций Gemini. Главное — «не знаю» только ПОСЛЕ поиска: без этого модель на вопрос о цене,
# которой нет в промпте, отвечала «не знаю» (звонок 01.11.2026), хотя база знаний была подключена.
GEMINI_TOOLS_POLICY = (
    "\n\nФУНКЦИИ. Если ответ прямо есть в твоей инструкции выше (о компании, готовые ответы на частые "
    "вопросы, прайс, история клиента) — отвечай сам и сразу, это не повод вызывать функцию. Если ответа "
    "там нет — вызови подходящую функцию (поиск по базе знаний, подбор по каталогу, поиск клиента) и "
    "ДОЖДИСЬ результата: пока не поискал, не говори «не знаю», «не могу» или «у меня нет такой "
    "информации». Получив результат, ответь по нему одной-двумя короткими фразами. Если поиск ничего не "
    "дал — честно скажи, что уточнишь у менеджера, и предложи прислать ответ после звонка; ничего не "
    "выдумывай. Не вызывай больше двух функций подряд, не сказав ничего собеседнику. Названия функций "
    "собеседнику не произноси и не рассказывай, что ищешь. Действие (запись, письмо, завершение "
    "звонка) считай выполненным только после успешного ответа функции."
)


def gemini_tools_hint(functions: Optional[List[Dict[str, Any]]]) -> str:
    """Одна строка на функцию: что делает и когда вызывать (первое предложение описания)."""
    rows = []
    for f in functions or []:
        name = f.get("name")
        if not name:
            continue
        desc = " ".join(str(f.get("description") or "").split())
        first = desc.split(". ")[0][:140].rstrip(".")
        rows.append(f"- {name}: {first}" if first else f"- {name}")
    if not rows:
        return ""
    return "\nДоступные функции (вызывай по делу, названия не произноси):\n" + "\n".join(rows[:12])


def build_gemini_voice_hints(functions: Optional[List[Dict[str, Any]]], voice: str, telephony: bool) -> str:
    """Всё, что дописывается к промпту карточки для Gemini Live (порядок как у GPT-Live)."""
    out = GEMINI_PRIORITY_NOTE + VOICE_MANNER_HINT + GEMINI_CONVERSATION_HINT + GEMINI_TOOLS_POLICY + gemini_tools_hint(functions) + VOICE_DIALOG_RULES + VOICE_GREETING_RULE
    if telephony:
        out += VOICE_TELEPHONY_HINT
    out += voice_gender_hint(voice)
    return out
