def _voice_gender(voice: str) -> Optional[str]:
    from backend.websockets.live_client import _FEMININE_VOICES, _MASCULINE_VOICES
    v = (voice or "").strip().lower()
    if v in _MASCULINE_VOICES:
        return "m"
    if v in _FEMININE_VOICES:
        return "f"
    return None


_KY_WORDS = ("саламатсыз", "кандайсыз", "жардам", "кантип", "рахмат", "сиз", "мен ", "биз ", "ооба", "макул")


def greeting_language(greeting: Optional[str], fallback: Optional[str]) -> Optional[str]:
    """Язык фразы приветствия (с неё модель начинает): кыргызские буквы/слова → ky, иная кириллица → ru."""
    text = (greeting or "").strip().lower()
    if not text:
        return fallback
    if any(ch in text for ch in "ңөү") or any(w in text + " " for w in _KY_WORDS):
        return "ky"
    if any("а" <= ch <= "я" or ch == "ё" for ch in text):
        return "ru"
    return fallback


