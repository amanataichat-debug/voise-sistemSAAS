_LANGUAGE_NAMES = {"ky": "кыргызском", "kk": "казахском", "uz": "узбекском", "en": "английском", "tr": "турецком", "ru": "русском"}


def language_note(language: str) -> str:
    """
    Язык карточки для Gemini Live — тот же порядок, что в промпте звонков агента (VOICE_AGENT_PROMPT_BASE):
    начни на языке приветствия и держись его; смени язык, только если собеседник целой фразой заговорил на другом
    (русский или кыргызский) или попросил; одно слово, акцент и короткое «алло» — не повод.
    """
    name = _LANGUAGE_NAMES.get((language or "").strip().lower()[:2])
    if not name:
        return ""
    return (f"\n\nЯЗЫК РАЗГОВОРА. Начни на {name} языке (приветствие) и держись его. Смени язык (русский или "
            "кыргызский), только если собеседник целой фразой заговорил на другом языке или попросил об этом, а "
            "вернулся обратно — вернись и ты. Не меняй язык из-за акцента, одного слова или короткого «алло». "
            "Никогда не говори, что плохо владеешь русским или кыргызским: не расслышал — мягко переспроси на его языке.")


# Правило функций Gemini. Главное — «не знаю» только ПОСЛЕ поиска: без этого модель на вопрос о цене,
# которой нет в промпте, отвечала «не знаю» (звонок 01.11.2026), хотя база знаний была подключена.
GEMINI_TOOLS_POLICY = (
    "\n\nФУНКЦИИ. Если ответ прямо есть в твоей инструкции выше (о компании, готовые ответы на частые "
    "вопросы, прайс, история клиента) — отвечай сам и сразу, это не повод вызывать функцию. Если ответа "
    "там нет — вызови подходящую функцию (поиск по базе знаний, подбор по каталогу, поиск клиента) и "
    "ДОЖДИСЬ результата: пока не поискал, не говори «не знаю», «не могу» или «у меня нет такой "
    "информации». Получив результат, ответь по нему одной-двумя короткими фразами. Если поиск ничего не "
    "дал — честно скажи, что уточнишь у менеджера, и предложи прислать ответ после звонка; ничего не "
    "выдумывай. Не вызывай больше двух функций подряд, не сказав ничего собеседнику. Названия функций "
    "собеседнику не произноси и не рассказывай, что ищешь. Действие (запись, письмо, завершение "
    "звонка) считай выполненным только после успешного ответа функции."
)


def gemini_tools_hint(functions: Optional[List[Dict[str, Any]]]) -> str:
    """Одна строка на функцию: что делает и когда вызывать (первое предложение описания)."""
    rows = []
    for f in functions or []:
        name = f.get("name")
        if not name:
            continue
        desc = " ".join(str(f.get("description") or "").split())
        first = desc.split(". ")[0][:140].rstrip(".")
        rows.append(f"- {name}: {first}" if first else f"- {name}")
    if not rows:
        return ""
    return "\nДоступные функции (вызывай по делу, названия не произноси):\n" + "\n".join(rows[:12])


def build_gemini_voice_hints(functions: Optional[List[Dict[str, Any]]], voice: str, telephony: bool) -> str:
    """Всё, что дописывается к промпту карточки для Gemini Live (порядок как у GPT-Live)."""
    # VOICE_DIALOG_RULES начинается без перевода строки — без "\n" он слипался с последней функцией списка
    out = (GEMINI_PRIORITY_NOTE + GEMINI_MANNER_HINT + GEMINI_TOOLS_POLICY + gemini_tools_hint(functions) + "\n"
           + VOICE_DIALOG_RULES + VOICE_GREETING_RULE)
    if telephony:
        out += VOICE_TELEPHONY_HINT
    out += voice_gender_hint(voice)
    return out
