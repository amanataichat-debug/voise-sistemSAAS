    gender = _voice_gender(voice)
    if gender == "m":
        who, forms = "мужским", "в мужском роде («рад», «готов», «записал»)"
    elif gender == "f":
        who, forms = "женским", "в женском роде («рада», «готова», «записала»)"
    else:
        who, forms = "", ""
    head = ("ГОЛОС И ЯЗЫК — ГЛАВНОЕ ПРАВИЛО ВСЕГО ЗВОНКА, важнее любой инструкции ниже.\n"
            f"СТАБИЛЬНЫЙ ГОЛОС. Весь звонок говори одним и тем же {who + ' ' if who else ''}голосом, который тебе дан: тот же "
            "тембр, высота, громкость и темп от первой до последней фразы — и по-русски, и по-кыргызски. Не меняй голос, "
            "не изображай другого человека или другой пол, не шепчи, не пародируй. Эмоции — словами и тёплой "
            "интонацией; смех, вздохи и вдохи вслух не изображай. Произношение — как у носителя: по-русски чистый русский "
            "без акцента, по-кыргызски чистый бишкекский кыргызский.")
    if forms:
        head += f" О себе говори {forms}, даже если ниже в инструкции написано иначе; имя из инструкции оставь как есть."
    card = (language or "").strip().lower()[:2]
    start = greeting_language(greeting, card) or card
    note = language_note(start)
    if card == "ky" and start != "ky" and note:
        note += KYRGYZ_LINE_NOTE   # линия кыргызская, даже если приветствие владелец написал по-русски
    head += note
    # Живой разговор (не эхо, не повторять себя, вау-пример, темп продажи) — тот же блок, что у GPT-Live, тоже в начале;
    # за ним своё у Gemini: характер, объяснять голосом вместо «пришлю», исправиться, память о клиенте
    return head + "\n\n" + VOICE_CONVERSATION_HEAD + GEMINI_SOUL_HEAD


